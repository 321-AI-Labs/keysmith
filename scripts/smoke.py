"""Smoke check: keysmith round-trips end to
end against an in-process fake upstream.

Checks: (1) a chat request with the WRONG client token -> 401; (2) a chat
request with the right token -> 200, content round-trips, the fake upstream
saw the REWRITTEN model and the right Bearer key; (3) at least one spend-log
line containing the key ALIAS and not the key value. Prints PASS/FAIL per
item; exits 0 only if all pass. Everything runs on loopback; no real keys.
"""

from __future__ import annotations

import json
import os
import pathlib
import shutil
import sys
import tempfile
import urllib.error
import urllib.request

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1]))

from keysmith.config import load_config
from keysmith.redact import SecretVault
from keysmith.server import KeysmithServer
from keysmith.spendlog import SpendLog
from tests.fake_upstream import FakeUpstream

TOKEN = "smoke-token-123"
KEY_ONE = "SMOKE_KEY_ONE"
KEY_TWO = "SMOKE_KEY_TWO"
KEY_ONE_VALUE = "sk-smoke-one-AAA"
KEY_TWO_VALUE = "sk-smoke-two-BBB"
MARKER = "round-trip-marker-42"


def _chat(url: str, token: str) -> tuple[int, bytes]:
    payload = json.dumps(
        {"model": "fake/fake-model", "messages": [{"role": "user", "content": MARKER}]}
    ).encode("utf-8")
    request = urllib.request.Request(
        url + "/v1/chat/completions",
        data=payload,
        method="POST",
        headers={"Authorization": f"Bearer {token}", "Content-Type": "application/json"},
    )
    try:
        with urllib.request.urlopen(request, timeout=15) as response:
            return response.status, response.read()
    except urllib.error.HTTPError as exc:
        with exc:
            return exc.code, exc.read()


def main() -> int:
    results: list[tuple[str, bool, str]] = []
    fake = FakeUpstream()
    fake.start()
    saved_env = {name: os.environ.get(name) for name in (KEY_ONE, KEY_TWO)}
    os.environ[KEY_ONE] = KEY_ONE_VALUE
    os.environ[KEY_TWO] = KEY_TWO_VALUE
    tmp = tempfile.mkdtemp(prefix="keysmith-smoke-")
    server = None
    try:
        config_path = pathlib.Path(tmp) / "providers.json"
        config_path.write_text(
            json.dumps(
                {
                    "_comment": "generated by scripts/smoke.py — points at the in-process fake upstream",
                    "providers": {
                        "fake": {
                            "base_url": fake.url,
                            "keys": [KEY_ONE, KEY_TWO],
                            "models": {"fake-model": "upstream-model-x"},
                            "cooldown_seconds": 60.0,
                            "timeout_seconds": 30.0,
                            "allow_insecure": True,
                        }
                    },
                }
            ),
            encoding="utf-8",
        )
        cfg = load_config(config_path)
        spend_path = pathlib.Path(tmp) / "spend.jsonl"
        server = KeysmithServer(
            cfg, TOKEN, SpendLog(spend_path), SecretVault(), host="127.0.0.1", port=0
        )
        server.start()

        # 1. wrong client token -> 401
        try:
            status, _body = _chat(server.url, "wrong-token")
            results.append(("wrong client token rejected with 401", status == 401, f"status={status}"))
        except Exception as exc:  # noqa: BLE001 - smoke reports, never crashes
            results.append(("wrong client token rejected with 401", False, repr(exc)))

        # 2. right token -> 200 round-trip with routing verified
        try:
            status, body = _chat(server.url, TOKEN)
            ok = status == 200
            detail = f"status={status}"
            if ok:
                parsed = json.loads(body)
                content = parsed["choices"][0]["message"]["content"]
                model = parsed.get("model")
                ok = ok and MARKER in content and model == "upstream-model-x"
                detail += f" model={model} marker={'yes' if MARKER in content else 'no'}"
            recorded = fake.requests()
            if recorded:
                seen_auth = recorded[-1].authorization
                seen_model = json.loads(recorded[-1].body).get("model")
                ok = ok and seen_auth == "Bearer " + KEY_ONE_VALUE and seen_model == "upstream-model-x"
                detail += (
                    f" upstream_auth={'ok' if seen_auth == 'Bearer ' + KEY_ONE_VALUE else seen_auth}"
                    f" upstream_model={seen_model}"
                )
            else:
                ok = False
                detail += " upstream recorded no requests"
            results.append(
                ("right token round-trips with rewritten model + key", ok, detail)
            )
        except Exception as exc:  # noqa: BLE001
            results.append(("right token round-trips with rewritten model + key", False, repr(exc)))

        # 3. spend log written with key alias, no key value
        try:
            text = spend_path.read_text(encoding="utf-8") if spend_path.exists() else ""
            lines = sum(1 for line in text.splitlines() if line.strip())
            has_alias = KEY_ONE in text or KEY_TWO in text
            leaks_value = KEY_ONE_VALUE in text or KEY_TWO_VALUE in text
            ok = lines >= 1 and has_alias and not leaks_value
            results.append(
                (
                    "spend log written with key alias, no key value",
                    ok,
                    f"lines={lines} alias={'yes' if has_alias else 'no'} value_leak={'yes' if leaks_value else 'no'}",
                )
            )
        except Exception as exc:  # noqa: BLE001
            results.append(("spend log written with key alias, no key value", False, repr(exc)))
    finally:
        if server is not None:
            server.stop()
        fake.stop()
        shutil.rmtree(tmp, ignore_errors=True)
        for name, value in saved_env.items():
            if value is None:
                os.environ.pop(name, None)
            else:
                os.environ[name] = value

    failures = [name for name, ok, _detail in results if not ok]
    for name, ok, detail in results:
        print(f"{'PASS' if ok else 'FAIL'}: {name} ({detail})")
    print(f"smoke: {len(results) - len(failures)}/{len(results)} checks passed")
    return 0 if not failures else 1


if __name__ == "__main__":
    raise SystemExit(main())
